const handleAlert = (alert: RealtimeAlert) => {
  emit('alertHandled', alert)
  
  // 从列表中移除已处理的警报
  const index = realtimeAlerts.value.findIndex(a => a.id === alert.id)
  if (index > -1) {
    realtimeAlerts.value.splice(index, 1)
  }
  
  ElMessage.success('警报已处理')
}

const saveDashboardConfig = () => {
  emit('configChanged', dashboardConfig.value)
  ElMessage.success('配置保存成功')
  showDashboardSettings.value = false
}

const startAutoRefresh = () => {
  if (refreshTimer.value) {
    clearInterval(refreshTimer.value)
  }
  
  refreshTimer.value = window.setInterval(() => {
    if (viewMode.value === 'realtime') {
      updateRealtimeData()
    } else {
      refreshAllData()
    }
  }, props.refreshInterval)
}

// 生命周期
onMounted(() => {
  refreshAllData()
  startAutoRefresh()
})

onBeforeUnmount(() => {
  if (refreshTimer.value) {
    clearInterval(refreshTimer.value)
  }
})
