const getProgressColor = (current: number, target: number) => {
  const ratio = current / target
  if (ratio >= 0.9) return '#67c23a'
  if (ratio >= 0.7) return '#e6a23c'
  return '#f56c6c'
}

const getHealthLevel = (score: number) => {
