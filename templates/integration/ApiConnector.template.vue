const handleEndpointAction = (command: string) => {
  const [action, endpointId] = command.split('-')
  const endpoint = apiEndpoints.value.find(ep => ep.id === endpointId)
  
  if (!endpoint) return
  
  switch (action) {
    case 'copy':
      navigator.clipboard.writeText(`${connectorConfig.value.baseUrl}${endpoint.path}`)
      ElMessage.success('链接已复制到剪贴板')
      break
    case 'docs':
      // 生成API文档
      ElMessage.info('生成文档功能开发中')
      break
    case 'history':
      // 查看调用历史
      ElMessage.info('调用历史功能开发中')
      break
    case 'toggle':
      endpoint.enabled = !endpoint.enabled
      ElMessage.success(`端点已${endpoint.enabled ? '启用' : '禁用'}`)
      break
    case 'delete':
      deleteEndpoint(endpoint)
      break
  }
}

